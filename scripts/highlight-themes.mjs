#!/usr/bin/env node

// Builds the default read-along highlight theme from highlighter inks, `--write` to update the code and docs
// The rules are documented in docs/customization/HighlightThemes.md

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const THEMES_FILE = "src/preferences/models/theme.ts";
const READIUM_COLORS_FILE = "node_modules/@readium/css/css/vars/colors.json";
const HIGHLIGHT_FILE = "src/preferences/models/readAlong.ts";
const DOCS_FILE = "docs/customization/HighlightThemes.md";

const HIGHLIGHT_START = "const defaultReadAlongHighlightTheme: Record<ThThemeKeys, ThReadAlongHighlightColors> = {\n";
const HIGHLIGHT_END = "\n};\n";
const DOCS_START = "<!-- highlight-themes:start · GENERATED by `pnpm highlight-themes --write`, do not edit until highlight-themes:end, edit scripts/highlight-themes.mjs instead -->\n";
const DOCS_END = "<!-- highlight-themes:end · GENERATED -->";

const INKS = {
  yellow: "#fff44f",
  orange: "#ffa040",
  pink: "#ff6fae",
  red: "#ff4f5e",
  green: "#3fd97a",
  blue: "#45c4f0"
};

// Darkened, they turn olive and brown
const NO_DARKENING = ["yellow", "orange"];

// Sentence fills on dark pages: the ink with its channels scaled down
const DIM_FACTORS = [0.28, 0.34, 0.4];

const LINE_CONTRAST = 3;
const TEXT_CONTRAST = 4.5;
const MASK_ALPHA = "99";

const SURFACES = ["onPage", "onFill", "onLine", "onText"];

// A highlighted word on a highlighted sentence is orange on yellow, as in most reading apps
const SENTENCE_FILL_INK = "yellow";
const WORD_ON_SENTENCE_FILL_INK = "orange";

// Every reading theme needs an entry: the inks it can't use otherwise, and the sentence fills to try
const THEME_CONFIG = {
  light: { exclude: [], fills: ["#fff44f"] },
  dark: { exclude: [], fills: "dim" },
  paper: { exclude: [], fills: ["#fff44f"] },
  sepia: { exclude: [], fills: ["#ffef3a"] },
  contrast1: { exclude: ["yellow"], fills: "dim" },
  contrast2: { exclude: ["blue"], fills: "dim" },
  contrast3: { exclude: ["green"], fills: ["#fff44f"] }
};

// Colors

const toRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
const toHex = (rgb) => "#" + rgb.map((x) => Math.round(Math.max(0, Math.min(1, x)) * 255).toString(16).padStart(2, "0")).join("");

const luminance = (hex) => {
  const [r, g, b] = toRgb(hex).map((x) => x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const hue = (hex) => {
  const [r, g, b] = toRgb(hex);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const delta = max - min;
  if (delta === 0) return 0;
  let h;
  if (max === r) h = ((g - b) / delta) % 6;
  else if (max === g) h = (b - r) / delta + 2;
  else h = (r - g) / delta + 4;
  return ((h * 60) + 360) % 360;
};

const chroma = (hex) => {
  const rgb = toRgb(hex);
  return Math.max(...rgb) - Math.min(...rgb);
};

const hueDistance = (a, b) => {
  const d = Math.abs(hue(a) - hue(b));
  return Math.min(d, 360 - d);
};

const isRed = (hex) => hue(hex) >= 330 || hue(hex) <= 20;
const isGreen = (hex) => hue(hex) >= 85 && hue(hex) <= 165;
const isRedGreen = (a, b) => (isRed(a) && isGreen(b)) || (isGreen(a) && isRed(b));

const textOn = (hex) => contrast(hex, "#000000") >= contrast(hex, "#ffffff") ? "#000000" : "#ffffff";

const dim = (hex, factor) => toHex(toRgb(hex).map((x) => x * factor));

const isLight = (hex) => luminance(hex) > 0.18;

// Toward black on light surfaces, toward white on dark ones, until the target is reached
const shade = (inkName, ink, surface, target) => {
  if (contrast(ink, surface) >= target) return ink;
  if (NO_DARKENING.includes(inkName) && isLight(surface)) return ink;
  const to = isLight(surface) ? 0 : 1;
  let color = ink;
  for (let i = 1; i <= 100; i++) {
    const k = i / 100;
    color = toHex(toRgb(ink).map((x) => x + (to - x) * k));
    if (contrast(color, surface) >= target) return color;
  }
  return color;
};

// Scores, from 0 to 1

const ratio = (value, target) => Math.min(value / target, 1);

const distinctText = (a, b) => {
  const c = contrast(a, b);
  if (chroma(a) < 0.25 || chroma(b) < 0.25) {
    return Math.max(chroma(a), chroma(b)) >= 0.5 ? ratio(c, 2) : ratio(c, 3);
  }
  if (!isRedGreen(a, b) && (hueDistance(a, b) >= 90 || (hueDistance(a, b) >= 45 && c >= 1.5))) return 1;
  return ratio(c, 3);
};

const distinctFill = (a, b) => {
  if (chroma(a) >= 0.25 && chroma(b) >= 0.25 && hueDistance(a, b) >= 45 && !isRedGreen(a, b)) return 1;
  return ratio(contrast(a, b), 2);
};

// Each cell returns the color an ink resolves to and its score
const wordCells = ({ page, pageText, fill, line, text }) => {
  const fillText = textOn(fill);
  const lineOn = (surface, extra = () => 1) => (name, ink) => {
    const color = shade(name, ink, surface, LINE_CONTRAST);
    return [color, Math.min(ratio(contrast(color, surface), LINE_CONTRAST), extra(color))];
  };
  const textOnSurface = (surface, extra = () => 1) => (name, ink) => {
    const color = shade(name, ink, surface, TEXT_CONTRAST);
    return [color, Math.min(ratio(contrast(color, surface), TEXT_CONTRAST), extra(color))];
  };

  return {
    fill: {
      onPage: (_, ink) => [ink, distinctFill(ink, page)],
      onFill: (name, ink) => [ink, name === WORD_ON_SENTENCE_FILL_INK ? distinctFill(ink, fill) : 0],
      onLine: (_, ink) => [ink, Math.min(ratio(contrast(line, ink), LINE_CONTRAST), distinctFill(ink, page), isRedGreen(line, ink) ? 0 : 1)],
      onText: (_, ink) => [ink, distinctFill(ink, text)]
    },
    line: {
      onPage: lineOn(page),
      onFill: lineOn(fill),
      onLine: lineOn(page, (c) => distinctText(c, line)),
      onText: lineOn(page, (c) => distinctText(c, text))
    },
    text: {
      onPage: textOnSurface(page, (c) => distinctText(c, pageText)),
      onFill: textOnSurface(fill, (c) => distinctText(c, fillText)),
      onLine: textOnSurface(page, (c) => Math.min(distinctText(c, pageText), distinctText(c, line))),
      onText: textOnSurface(page, (c) => distinctText(c, text))
    }
  };
};

const compare = (a, b) => {
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return a[i] > b[i] ? 1 : -1;
  }
  return 0;
};

const round3 = (x) => Math.round(x * 1000) / 1000;

// A main ink, and an alternate one used only in the cells where the main one does worse
const bestPair = (cells, inks) => {
  let best = null;
  for (const [a, inkA] of inks) {
    for (const [b, inkB] of inks) {
      const row = {};
      for (const surface of SURFACES) {
        const [colorA, scoreA] = cells[surface](a, inkA);
        const [colorB, scoreB] = cells[surface](b, inkB);
        row[surface] = scoreA >= scoreB - 1e-9 ? { ink: a, color: colorA, score: scoreA } : { ink: b, color: colorB, score: scoreB };
      }
      const scores = SURFACES.map((s) => row[s].score);
      const used = new Set(SURFACES.map((s) => row[s].ink));
      const key = [Math.min(...scores), scores.reduce((x, y) => x + y, 0), -used.size, a === b ? 1 : 0];
      if (!best || compare(key, best.key) > 0) best = { key, row };
    }
  }
  return best;
};

const fillCandidates = (fills) => {
  if (Array.isArray(fills)) return fills;
  if (fills === "dim") return DIM_FACTORS.map((f) => dim(INKS[SENTENCE_FILL_INK], f));
  throw new Error(`Unknown fills: "${ fills }"`);
};

const solveTheme = ({ page, pageText }, { exclude, fills }) => {
  const inks = Object.entries(INKS).filter(([name]) => !exclude.includes(name));
  let best = null;

  for (const fill of fillCandidates(fills)) {
    if (contrast(textOn(fill), fill) < TEXT_CONTRAST) continue;
    // The DOM overlay multiplies fills on light pages, so a dark fill would blacken its own text
    if (isLight(page) && textOn(fill) !== "#000000") continue;

    for (const [lineName, lineInk] of inks) {
      for (const [textName, textInk] of inks) {
        const line = shade(lineName, lineInk, page, LINE_CONTRAST);
        const text = shade(textName, textInk, page, TEXT_CONTRAST);
        const lineScore = Math.min(ratio(contrast(line, page), LINE_CONTRAST), distinctText(line, pageText));
        const textScore = Math.min(ratio(contrast(text, page), TEXT_CONTRAST), distinctText(text, pageText));

        const cells = wordCells({ page, pageText, fill, line, text });
        const word = {};
        let min = Math.min(lineScore, textScore);
        let total = lineScore + textScore;
        for (const kind of ["fill", "line", "text"]) {
          const pair = bestPair(cells[kind], inks);
          word[kind] = pair.row;
          min = Math.min(min, pair.key[0]);
          total += pair.key[1];
        }

        const key = [round3(min), round3(total)];
        if (!best || compare(key, best.key) > 0) {
          best = { key, utterance: { fill, line, text, mask: page + MASK_ALPHA }, word };
        }
      }
    }
  }
  return best;
};

// Inputs

const readThemes = () => {
  const source = fs.readFileSync(path.join(root, THEMES_FILE), "utf-8");
  const readiumColors = JSON.parse(fs.readFileSync(path.join(root, READIUM_COLORS_FILE), "utf-8"));
  const resolve = (value, name) => {
    const readium = value.match(/^ReadiumCSSColors\.(\w+)$/);
    const color = readium ? readiumColors[readium[1]] : value.replace(/["']/g, "");
    if (!/^#[0-9a-fA-F]{6}$/.test(color ?? "")) throw new Error(`${ name }: can't resolve "${ value }" to a #rrggbb color`);
    return color.toLowerCase();
  };

  const themes = {};
  for (const match of source.matchAll(/export const (\w+)Theme = \{([\s\S]*?)\n\};?(?=\n|$)/g)) {
    const [, key, body] = match;
    const background = body.match(/^\s*background:\s*([^,\n]+?),?\s*(\/\/.*)?$/m);
    const text = body.match(/^\s*text:\s*([^,\n]+?),?\s*(\/\/.*)?$/m);
    if (!background || !text) throw new Error(`${ key }Theme: no background or text color`);
    themes[key] = { page: resolve(background[1], key), pageText: resolve(text[1], key) };
  }
  if (!Object.keys(themes).length) throw new Error(`${ THEMES_FILE }: no reading themes found`);
  return themes;
};

// Outputs

const renderCode = (results) => {
  const row = (colors) => "{ " + SURFACES.map((s) => `${ s }: "${ colors[s].color }"`).join(", ") + " }";
  return Object.entries(results).map(([key, { utterance: u, word }]) => [
    `  [ThThemeKeys.${ key }]: {`,
    `    utterance: { fill: "${ u.fill }", line: "${ u.line }", text: "${ u.text }", mask: "${ u.mask }" },`,
    "    word: {",
    `      fill: ${ row(word.fill) },`,
    `      line: ${ row(word.line) },`,
    `      text: ${ row(word.text) }`,
    "    }",
    "  }"
  ].join("\n")).join(",\n");
};

const describe = (color, ink) => {
  if (Object.values(INKS).includes(color)) return `${ ink } \`${ color }\``;
  return `dark ${ ink } \`${ color }\``;
};

const describeFill = (fill) => {
  const ink = Object.entries(INKS).find(([, value]) => value === fill);
  if (ink) return `${ ink[0] } \`${ fill }\``;
  if (fill === "#000000") return "black `#000000`";
  const dimmed = Object.entries(INKS).find(([, value]) => DIM_FACTORS.some((f) => dim(value, f) === fill));
  if (dimmed) return `dim ${ dimmed[0] } \`${ fill }\``;
  return `\`${ fill }\``;
};

const renderDocs = (themes, results, sentenceInks) => {
  const out = [];
  for (const [key, result] of Object.entries(results)) {
    const { page, pageText } = themes[key];
    const { utterance: u, word } = result;
    out.push(`\`${ key }\`, page \`${ page }\`, text \`${ pageText }\`:`, "");
    out.push("| | Fill | Line | Text |", "|---|---|---|---|");
    out.push(`| Sentence | ${ describeFill(u.fill) } | ${ describe(u.line, sentenceInks[key].line) } | ${ describe(u.text, sentenceInks[key].text) } |`);
    for (const s of SURFACES) {
      out.push(`| Word, \`${ s }\` | ${ describe(word.fill[s].color, word.fill[s].ink) } | ${ describe(word.line[s].color, word.line[s].ink) } | ${ describe(word.text[s].color, word.text[s].ink) } |`);
    }
    out.push("");
  }

  const limits = [];
  for (const [key, { word }] of Object.entries(results)) {
    for (const kind of ["fill", "line", "text"]) {
      for (const s of SURFACES) {
        if (word[kind][s].score < 1) limits.push(`\`${ key }\` \`word.${ kind }.${ s }\` (${ Math.round(word[kind][s].score * 100) }%)`);
      }
    }
  }
  out.push("Colors that don’t fully meet their requirements, with how close they get: " + (limits.length ? limits.join(", ") : "none") + ".");
  return out.join("\n") + "\n";
};

const replaceBetween = (content, start, end, replacement, file) => {
  const a = content.indexOf(start);
  const b = content.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`${ file }: markers not found`);
  return content.slice(0, a + start.length) + replacement + content.slice(b);
};

// Main

const themes = readThemes();
const missing = Object.keys(themes).filter((key) => !THEME_CONFIG[key]);
if (missing.length) {
  console.error(`Add ${ missing.join(", ") } to THEME_CONFIG in scripts/highlight-themes.mjs`);
  process.exit(1);
}
const unknown = Object.keys(THEME_CONFIG).filter((key) => !themes[key]);
if (unknown.length) {
  console.error(`${ unknown.join(", ") } in THEME_CONFIG not found in ${ THEMES_FILE }`);
  process.exit(1);
}

const results = {};
const sentenceInks = {};
for (const key of Object.keys(themes)) {
  const result = solveTheme(themes[key], THEME_CONFIG[key]);
  results[key] = result;
  const inks = Object.entries(INKS).filter(([name]) => !THEME_CONFIG[key].exclude.includes(name));
  const find = (color, target) => inks.find(([name, ink]) => shade(name, ink, themes[key].page, target) === color)?.[0];
  sentenceInks[key] = { line: find(result.utterance.line, LINE_CONTRAST), text: find(result.utterance.text, TEXT_CONTRAST) };

  const { utterance: u, word } = result;
  console.log(`${ key } (worst cell ${ Math.round(result.key[0] * 100) }%)`);
  console.log(`  sentence  fill ${ u.fill }  line ${ u.line }  text ${ u.text }`);
  for (const kind of ["fill", "line", "text"]) {
    console.log(`  word ${ kind.padEnd(4) } ` + SURFACES.map((s) => `${ s } ${ word[kind][s].color }`).join("  "));
  }
}

const highlightPath = path.join(root, HIGHLIGHT_FILE);
const docsPath = path.join(root, DOCS_FILE);
const code = fs.readFileSync(highlightPath, "utf-8");
const docs = fs.readFileSync(docsPath, "utf-8");
const nextCode = replaceBetween(code, HIGHLIGHT_START, HIGHLIGHT_END, renderCode(results), HIGHLIGHT_FILE);
const nextDocs = replaceBetween(docs, DOCS_START, DOCS_END, renderDocs(themes, results, sentenceInks), DOCS_FILE);

if (process.argv.includes("--write")) {
  fs.writeFileSync(highlightPath, nextCode);
  fs.writeFileSync(docsPath, nextDocs);
  console.log(`\nWrote ${ HIGHLIGHT_FILE } and ${ DOCS_FILE }`);
} else if (nextCode !== code || nextDocs !== docs) {
  console.error("\nOut of date, run with --write");
  process.exit(1);
}
